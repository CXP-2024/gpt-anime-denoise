"""Automatic "select the character" for the web app: SkyTNT's anime-segmentation (ISNet), Apache-2.0.

The network blocks below are copied unchanged from https://github.com/SkyTNT/anime-segmentation (model/isnet.py,
Apache License 2.0, itself based on https://github.com/xuebinqin/DIS); only the training losses and the GT encoder
were left out, and ISNetDIS returns just the finest side output. Weights: https://huggingface.co/skytnt/anime-seg
(model.safetensors, Apache-2.0), downloaded on first use and checked against SHA-256.
"""
import torch
import torch.nn as nn
import torch.nn.functional as F

URL = "https://huggingface.co/skytnt/anime-seg/resolve/main/model.safetensors"
NAME = "anime-seg_isnetis.safetensors"
