package com.animedenoise

import android.content.Context
import android.provider.MediaStore
import android.util.Log
import com.animedenoise.core.L0Smoother
import com.animedenoise.core.FloatImage
import com.animedenoise.core.PilResize
import com.animedenoise.core.RgbaImage
import com.animedenoise.image.ImageIo
import com.animedenoise.sr.ModelStore
import com.animedenoise.sr.Runtimes
import com.animedenoise.sr.SrModel
import java.util.Locale
import kotlin.math.abs

/**
 * On-device verification against the desktop reference.
 *
 * Run from adb:
 *   adb shell am broadcast -a com.animedenoise.SELFTEST
 *
 * Logs (tag "SelfTest") the byte-exact comparison of the pure-Kotlin stages against fixtures
 * generated by the real denoise.py, then times the ONNX session on each available backend.
 * This is what proves the phone reproduces the desktop output rather than merely looking similar.
 */
object SelfTest {

    private const val TAG = "SelfTest"

    fun run(context: Context) {
        attach(context)
        Thread({
            try {
                runCatching { runSyntheticBench() }.onFailure { log("bench failed: " + it) }
                runStages()
                runCatching { runEndToEnd(context) }.onFailure { log("end-to-end failed: " + it) }
                runCatching { runRealImage(context) }.onFailure { log("real-image run failed: " + it) }
                runInference(context)
            } catch (t: Throwable) {
                Log.e(TAG, "self test failed", t)
            }
            Log.i(TAG, "DONE")
        }, "selftest").start()
    }

    /**
     * Fixture-free L0 benchmark.
     *
     * The release APK ships no test images, and a release build cannot be inspected with run-as,
     * so this synthesises its own input. It answers the debug-vs-release question: debug builds run
     * interpreted at first, while release is AOT compiled by ART, which can change the L0 cost by
     * several times.
     */
    private fun runSyntheticBench() {
        for (side in intArrayOf(512, 1024)) {
            val img = com.animedenoise.core.FloatImage(side, side)
            for (c in 0 until 3) {
                val p = img.plane(c)
                for (i in p.indices) p[i] = ((i * 37 + c * 11) % 255) / 255f
            }
            val t0 = System.nanoTime()
            com.animedenoise.core.L0SmootherF32.smooth(img, 0.001)
            val ms = (System.nanoTime() - t0) / 1_000_000
            log("BENCH L0 " + side + "x" + side + " (" + (side * side / 1e6) + " MP): " + ms + " ms")
        }
    }

    /**
     * Runs the real 2160x3840 working image through the exact production path.
     *
     * The fixtures are 512x512 crops; this is the size the user actually works at, and the cost at
     * 8.3 MP is dominated by the model pass and the L0 solve, so it is the only number worth quoting.
     */
    private fun runRealImage(context: Context) {
        // Must live in the app's own storage: /sdcard/Download is not readable without the user
        // granting access through the system picker (scoped storage), which a background self test
        // cannot do. Push it with: adb push x.png /data/local/tmp/ then
        //   adb shell run-as com.animedenoise cp /data/local/tmp/x.png files/in_real.png
        // Debug builds get the image through run-as (files/in_real.png); release builds read it
        // from Pictures via MediaStore, which needs READ_MEDIA_IMAGES (adb can grant it).
        val private = java.io.File(context.filesDir, "in_real.png")
        var bitmap: android.graphics.Bitmap? = null
        if (private.isFile) {
            bitmap = android.graphics.BitmapFactory.decodeFile(private.absolutePath)
        } else {
            val resolver = context.contentResolver
            val collection = MediaStore.Images.Media.getContentUri(MediaStore.VOLUME_EXTERNAL_PRIMARY)
            resolver.query(
                collection,
                arrayOf(MediaStore.MediaColumns._ID),
                MediaStore.MediaColumns.DISPLAY_NAME + " = ?",
                arrayOf("in_real_full.png"),
                null,
            )?.use { cursor ->
                if (cursor.moveToFirst()) {
                    val uri = android.content.ContentUris.withAppendedId(collection, cursor.getLong(0))
                    resolver.openInputStream(uri)?.use { stream ->
                        bitmap = android.graphics.BitmapFactory.decodeStream(stream)
                    }
                }
            }
        }
        if (bitmap == null) {
            log("REAL image not available; skipping")
            return
        }
        val src = bitmap
        if (src == null) {
            log("real image could not be decoded")
            return
        }
        val input = ImageIo.fromBitmap(src)
        src.recycle()
        log("REAL image " + input.width + "x" + input.height + " = " +
            (input.width.toLong() * input.height / 1_000_000.0).toString().take(4) + " MP")

        // UI present: hand off to the ViewModel so the user sees the real progress flow, and
        // the timing numbers come back through the same channel.
        val listener = uiListener
        if (listener != null) {
            log("REAL handing off to UI")
            listener(input)
            return
        }

        val assets = assets()
        val model = SrModel.ANIMEVIDEOV3
        val engine = DenoiseEngine(context)
        try {
            engine.ensureModel(model, Runtimes.Backend.CPU)
            val t = System.nanoTime()
            val result = engine.denoise(src = input, down = 0.6, lam = 0.001, onStage = {})
            val secs = (System.nanoTime() - t) / 1_000_000_000.0
            val fast = input.width.toLong() * input.height >= 4_000_000L
            log("REAL pipeline total " + String.format(java.util.Locale.US, "%.1f", secs) + " s " +
                "(L0 " + (if (fast) "f32-fast" else "f64-exact") + ") stages=" + result.stageMillis)
            // Encode and report the output size so the result is usable.
            val png = ImageIo.encodePng(result.output)
            val outFile = java.io.File(context.filesDir, "out_real.png")
            outFile.writeBytes(png)
            log("REAL wrote " + outFile.length() / 1024 + " KB to " + outFile.absolutePath)
        } finally {
            engine.release()
        }
    }


    /**
     * Drives the real app pipeline: DenoiseEngine loads the ONNX session from assets, runs the model,
     * resizes back and smooths, exactly as a user's tap does. Compares the final PNG bytes against the
     * desktop reference for the default settings.
     *
     * This is the check that matters most: the unit tests exercise the pure-Kotlin stages, and
     * [runInference] exercises the session, but only this one proves the assembled app reproduces
     * denoise.py on the phone.
     */
    private fun runEndToEnd(context: Context) {
        val assets = assets()
        val input = png(assets, "tests/in_01ee25d8.png") ?: return
        val expected = png(assets, "tests/out_01ee25d8.png") ?: return
        val model = SrModel.bundled(ModelStore.available(assets)).firstOrNull() ?: return

        val engine = DenoiseEngine(context)
        try {
            val t0 = System.nanoTime()
            val backend = engine.ensureModel(model, Runtimes.Backend.CPU)
            log("E2E model loaded on " + backend + " in " + ms(t0))

            val t = System.nanoTime()
            val result = engine.denoise(
                src = input,
                down = 0.6,
                lam = 0.001,
                onStage = {},
            )
            val total = ms(t)
            log("E2E pipeline " + input.width + "x" + input.height + ": " + total +
                " stages=" + result.stageMillis)
            // The fixture is the desktop 6B reference. The bundled v3 model intentionally differs
            // from it (mean ~3.5 levels on line work), so this line reports the model gap, not an error.
            log("E2E output vs desktop 6B reference (expected gap, v3 != 6B): " + maxDiff(result.output, expected))

            // Second run at a different L0 strength must reuse the cached super-resolution result.
            val t2 = System.nanoTime()
            val again = engine.denoise(src = input, down = 0.6, lam = 0.0018, onStage = {})
            log("E2E L0-only rerun: " + ms(t2) + " reusedSuperResolution=" + again.reusedSuperResolution)
        } finally {
            engine.release()
        }
    }

    /**
     * The pure-Kotlin stages must be byte-identical to Pillow/numpy.
     *
     * Release builds bundle only the two end-to-end PNGs, so the per-stage gates run only when their
     * fixtures are present; that keeps the shipped APK small without shipping a broken check.
     */
    private fun runStages() {
        val assets = assets()
        val resizeSrc = png(assets, "tests/in_resize.png")
        val expectBox = png(assets, "tests/resize_boxed.png")
        val expectBack = png(assets, "tests/resize_back.png")

        if (resizeSrc != null && expectBox != null && expectBack != null) {
            var t = System.nanoTime()
            val sw = PilResize.pythonRoundSize(resizeSrc.width, 0.6)
            val sh = PilResize.pythonRoundSize(resizeSrc.height, 0.6)
            val box = PilResize.resize(resizeSrc, sw, sh, PilResize.Filter.BOX)
            log("BOX " + resizeSrc.width + "x" + resizeSrc.height + " -> " + sw + "x" + sh +
                ": maxDiff=" + maxDiff(box, expectBox) + " in " + ms(t))

            t = System.nanoTime()
            val back = PilResize.resize(box, resizeSrc.width, resizeSrc.height, PilResize.Filter.LANCZOS)
            log("LANCZOS back: maxDiff=" + maxDiff(back, expectBack) + " in " + ms(t))

            t = System.nanoTime()
            val box2 = PilResize.resize(resizeSrc, resizeSrc.width * 4, resizeSrc.height * 4,
                PilResize.Filter.LANCZOS)
            log("LANCZOS upscale timing: " + ms(t) + " (" + box2.width + "x" + box2.height + ")")
        } else {
            log("resize gates skipped: fixtures not bundled in this build")
        }

        val mid = npy(assets, "tests/mid_01ee25d8.npy")
        val expectOut = png(assets, "tests/out_01ee25d8.png")
        if (mid != null && expectOut != null) {
            val t = System.nanoTime()
            val smoothed = L0Smoother.smooth(mid, 0.001)
            val got = FloatImage.toRgba(smoothed, null)
            log("L0 " + mid.width + "x" + mid.height + ": maxDiff=" + maxDiff(got, expectOut) +
                " in " + ms(t) + " cpuThreads=" + Runtime.getRuntime().availableProcessors())
        } else {
            log("L0 gate skipped: mid fixture not bundled in this build")
        }
    }

    /**
     * Introspects what the Android ONNX Runtime build actually hands back, because its wrapper classes
     * differ from the desktop jar: the JVM tests can pass while the phone fails.
     */
    private fun probeRuntime(context: Context) {
        val assets = assets()
        val model = SrModel.bundled(ModelStore.available(assets)).firstOrNull() ?: return
        val env = ai.onnxruntime.OrtEnvironment.getEnvironment()
        val bytes = ModelStore.readBytes(assets, model.assetName)
        val opts = ai.onnxruntime.OrtSession.SessionOptions().apply {
            setOptimizationLevel(ai.onnxruntime.OrtSession.SessionOptions.OptLevel.ALL_OPT)
        }
        val session = env.createSession(bytes, opts)
        val outName = session.outputNames.first()
        val info = session.outputInfo[outName]
        log("PROBE outputInfo class=" + (info?.javaClass?.name ?: "null"))
        if (info != null) {
            for (f in info.javaClass.declaredFields) {
                log("PROBE field " + f.name + ":" + f.type.name)
            }
            for (m in info.javaClass.methods.filter { it.name.startsWith("get") || it.name.startsWith("is") }) {
                log("PROBE method " + m.name + "():" + m.returnType.name)
            }
        }
        // Run a tiny tensor straight through and inspect the returned container.
        val input = png(assets, "tests/in_resize.png")
            ?.let { PilResize.resize(it, 32, 32, PilResize.Filter.BOX) }
        if (input != null) {
            val plane = 32 * 32
            val buf = java.nio.ByteBuffer.allocateDirect(3 * plane * 4)
                .order(java.nio.ByteOrder.nativeOrder()).asFloatBuffer()
            for (p in 0 until plane) {
                val o = p * 4
                buf.put(p, (input.pixels[o].toInt() and 0xFF) / 255f)
                buf.put(plane + p, (input.pixels[o + 1].toInt() and 0xFF) / 255f)
                buf.put(2 * plane + p, (input.pixels[o + 2].toInt() and 0xFF) / 255f)
            }
            buf.position(0)
            ai.onnxruntime.OnnxTensor.createTensor(
                env, buf, longArrayOf(1, 3, 32, 32),
            ).use { tensor ->
                session.run(mapOf(session.inputNames.first() to tensor)).use { result ->
                    val v = result.get(outName)
                    log("PROBE result.get class=" + (v?.javaClass?.name ?: "null"))
                    v?.let { value ->
                        log("PROBE isOnnxTensor=" + (value is ai.onnxruntime.OnnxTensor) +
                            " isOnnxSequence=" + (value is ai.onnxruntime.OnnxSequence))
                        log("PROBE value type=" + runCatching { value.javaClass.getMethod("getValue").invoke(value) }
                            .map { it?.javaClass?.name ?: "null" }.getOrElse { "ERR " + it })
                    }
                    for (name in session.outputNames) {
                        log("PROBE name=" + name + " class=" + result.get(name)?.javaClass?.name)
                    }
                }
            }
        }
        session.close()
        opts.close()
    }

    /** Times one 4x inference per backend so the device picks the right default. */
    private fun runInference(context: Context) {
        val assets = assets()
        val model = SrModel.bundled(ModelStore.available(assets)).firstOrNull() ?: return
        val input = png(assets, "tests/in_resize.png")
            ?.let { PilResize.resize(it, 307, 307, PilResize.Filter.BOX) } ?: return
        val env = ai.onnxruntime.OrtEnvironment.getEnvironment()
        val bytes = ModelStore.readBytes(assets, model.assetName)
        Log.i(TAG, "model " + model.assetName + " = " + (bytes.size / 1024 / 1024) + " MB")
        // QNN is intentionally not probed here: its session creation segfaults natively on this SoC and
        // would take this process with it. See QnnProbeService.
        for (backend in listOf(
            Runtimes.Backend.CPU,
            Runtimes.Backend.XNNPACK,
            Runtimes.Backend.NNAPI,
        )) {
            try {
                val built = Runtimes.create(env, model, bytes, backend)
                built.runtime.use { runtime ->
                    // Warm up so shader/LLVM compilation is not counted.
                    runtime.upscale(input)
                    val t = System.nanoTime()
                    val out = runtime.upscale(input)
                    val elapsed = (System.nanoTime() - t) / 1_000_000
                    log("SR backend=" + built.runtime.backendName + " requested=" + backend.label +
                        " " + input.width + "x" + input.height + " -> " + out.width + "x" + out.height +
                        " in " + elapsed + " ms" + (built.note?.let { " note=" + it.trim() } ?: ""))
                }
            } catch (t: Throwable) {
                log("backend " + backend.label + " unavailable: " + (t.message ?: t.javaClass.simpleName))
            }
        }
    }

    private var contextRef: Context? = null

    private fun assets() = contextRef!!.assets

    private fun log(message: String) {
        Log.i(TAG, message)
        appendToFile(message)
    }

    /** Mirrors every line to app storage: a disconnect or crash would otherwise wipe logcat. */
    private fun appendToFile(message: String) {
        try {
            val ctx = contextRef ?: return
            java.io.File(ctx.filesDir, "selftest.log").appendText(message + "\n")
        } catch (t: Throwable) {
            Log.w(TAG, "cannot write selftest.log", t)
        }
    }

    private fun ms(startNanos: Long): String =
        String.format(Locale.US, "%.1f ms", (System.nanoTime() - startNanos) / 1_000_000.0)

    private fun maxDiff(a: RgbaImage, b: RgbaImage): String {
        if (a.width != b.width || a.height != b.height) {
            return "SIZE MISMATCH " + a.width + "x" + a.height + " vs " + b.width + "x" + b.height
        }
        var max = 0
        var count = 0
        for (i in a.pixels.indices) {
            val d = abs((a.pixels[i].toInt() and 0xFF) - (b.pixels[i].toInt() and 0xFF))
            if (d > 0) count++
            if (d > max) max = d
        }
        return max.toString() + " (differing bytes=" + count + ")"
    }

    fun attach(context: Context) {
        contextRef = context.applicationContext
    }

    /**
     * Set by the Activity when the self test should drive the visible UI.
     *
     * The self test historically ran in its own engine with no UI feedback, which made a two-minute
     * run look like the app had frozen. When [onSourceReady] is set, the test hands the decoded image
     * to the ViewModel and the user watches the real progress UI instead.
     */
    var uiListener: ((source: com.animedenoise.core.RgbaImage) -> Unit)? = null

    private fun png(assets: android.content.res.AssetManager, path: String): RgbaImage? = try {
        assets.open(path).use { stream ->
            val bitmap = android.graphics.BitmapFactory.decodeStream(stream) ?: return null
            ImageIo.fromBitmap(bitmap)
        }
    } catch (t: Throwable) {
        Log.w(TAG, "missing fixture " + path, t)
        null
    }

    /** Minimal reader for the float64 golden arrays, mirroring the JVM test helper. */
    private fun npy(assets: android.content.res.AssetManager, path: String): FloatImage? = try {
        val all = assets.open(path).use { it.readBytes() }
        val major = all[6].toInt()
        val headerLen: Int
        val headerStart: Int
        if (major == 1) {
            headerLen = (all[8].toInt() and 0xFF) or ((all[9].toInt() and 0xFF) shl 8)
            headerStart = 10
        } else {
            headerLen = (all[8].toInt() and 0xFF) or ((all[9].toInt() and 0xFF) shl 8) or
                ((all[10].toInt() and 0xFF) shl 16) or ((all[11].toInt() and 0xFF) shl 24)
            headerStart = 12
        }
        val header = String(all, headerStart, headerLen, Charsets.US_ASCII)
        val shapeText = Regex("'shape'\\s*:\\s*\\(([^)]*)\\)").find(header)!!.groupValues[1]
        val shape = shapeText.split(',').mapNotNull { it.trim().toIntOrNull() }
        val h = shape[0]
        val w = shape[1]
        val c = shape[2]
        val dataStart = headerStart + headerLen
        val buffer = java.nio.ByteBuffer.wrap(all).order(java.nio.ByteOrder.LITTLE_ENDIAN)
        val out = FloatImage(w, h)
        for (y in 0 until h) {
            for (x in 0 until w) {
                val base = dataStart + ((y * w + x) * c) * 8
                val i = y * w + x
                out.r[i] = buffer.getDouble(base).toFloat()
                out.g[i] = buffer.getDouble(base + 8).toFloat()
                out.b[i] = buffer.getDouble(base + 16).toFloat()
            }
        }
        out
    } catch (t: Throwable) {
        Log.w(TAG, "missing fixture " + path, t)
        null
    }
}
