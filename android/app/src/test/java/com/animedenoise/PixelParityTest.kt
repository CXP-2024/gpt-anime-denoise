package com.animedenoise

import com.animedenoise.core.FloatImage
import com.animedenoise.core.L0Smoother
import com.animedenoise.core.PilResize
import com.animedenoise.core.RgbaImage
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import kotlin.math.abs

/**
 * Pixel-parity tests against fixtures produced by the real denoise.py code path on CPU.
 *
 * These run on the JVM (no Android, no phone) because the whole image pipeline except the ONNX
 * session is pure Kotlin. A failure here means the port drifted from the Python reference, which
 * is exactly the bug class that would be invisible in a screenshot but visible to a user
 * comparing output on both platforms.
 *
 * Fixtures live in android/tools/golden and are regenerated by android/tools/generate_fixtures.py.
 * When they are absent (fresh clone, CI without the reference venv) the tests skip rather than fail.
 */
class PixelParityTest {

    private val goldenDir: File = locateGolden()

    private fun locateGolden(): File {
        var dir: File? = File(System.getProperty("user.dir") ?: ".").absoluteFile
        while (dir != null) {
            val candidate = File(dir, "tools/golden")
            if (candidate.isDirectory) return candidate
            dir = dir.parentFile
        }
        return File("tools/golden")
    }

    private fun fixture(tag: String): Triple<RgbaImage, FloatImage, RgbaImage>? {
        val input = File(goldenDir, "in_$tag.png")
        val mid = File(goldenDir, "mid_$tag.npy")
        val out = File(goldenDir, "out_$tag.png")
        if (!input.isFile || !mid.isFile || !out.isFile) return null
        return Triple(Png.read(input), Npy.readFloatImage(mid), Png.read(out))
    }

    /**
     * The shrunken size must match Python's round(W * 0.6). Python's round() is half-to-even, which
     * differs from Kotlin's Math.round on exact .5 values, so this is worth pinning.
     */
    @Test
    fun bankerRounding() {
        assertEquals(2, PilResize.pythonRoundSize(5, 0.5))   // round(2.5) -> 2
        assertEquals(4, PilResize.pythonRoundSize(7, 0.5))   // round(3.5) -> 4
        assertEquals(2, PilResize.pythonRoundSize(24, 0.1))  // round(2.4) -> 2
        assertEquals(512, PilResize.pythonRoundSize(512, 1.0))
        assertEquals(307, PilResize.pythonRoundSize(512, 0.6)) // round(307.2) -> 307
    }

    /** L0 must reproduce the float64 reference to within floating point noise. */
    @Test
    fun l0MatchesReference() {
        var checked = 0
        for (tag in TAGS) {
            val (_, mid, expectedOut) = fixture(tag) ?: continue
            val smoothed = L0Smoother.smooth(mid, 0.001)
            val got = FloatImage.toRgba(smoothed, null)
            val expected = expectedOut
            assertEquals("size for $tag", expected.pixels.size, got.pixels.size)
            var maxDiff = 0
            var totalDiff = 0L
            for (i in expected.pixels.indices) {
                val a = expected.pixels[i].toInt() and 0xFF
                val b = got.pixels[i].toInt() and 0xFF
                val d = abs(a - b)
                if (d > maxDiff) maxDiff = d
                totalDiff += d
            }
            val mean = totalDiff.toDouble() / expected.pixels.size
            println("[parity] L0 $tag: max byte diff = $maxDiff, mean = $mean")
            assertTrue("L0 drift for $tag: max byte diff $maxDiff (mean $mean)", maxDiff <= 2)
            checked++
        }
        if (checked == 0) println("[parity] L0 skipped: no fixtures in " + goldenDir)
    }

    /** BOX downscale + LANCZOS back must reproduce Pillow's pixels exactly. */
    @Test
    fun resizeMatchesPillow() {
        val input = File(goldenDir, "in_resize.png")
        val boxed = File(goldenDir, "resize_boxed.png")
        val lanczos = File(goldenDir, "resize_back.png")
        if (!input.isFile || !boxed.isFile || !lanczos.isFile) {
            println("[parity] resize skipped: fixtures missing in " + goldenDir)
            return
        }
        val src = Png.read(input)
        val expectedBox = Png.read(boxed)
        val expectedBack = Png.read(lanczos)
        val smallW = PilResize.pythonRoundSize(src.width, 0.6)
        val smallH = PilResize.pythonRoundSize(src.height, 0.6)

        val gotSmall = PilResize.resize(src, smallW, smallH, PilResize.Filter.BOX)
        assertEquals("BOX width", expectedBox.width, gotSmall.width)
        assertEquals("BOX height", expectedBox.height, gotSmall.height)
        val boxDiff = maxByteDiff(expectedBox, gotSmall)
        println("[parity] BOX downscale: max byte diff = " + boxDiff.max + ", differing pixels = " + boxDiff.count)
        assertEquals("BOX downscale must be byte exact", 0, boxDiff.max)

        val gotBack = PilResize.resize(gotSmall, src.width, src.height, PilResize.Filter.LANCZOS)
        val backDiff = maxByteDiff(expectedBack, gotBack)
        println("[parity] LANCZOS resize back: max byte diff = " + backDiff.max + ", differing pixels = " + backDiff.count)
        assertTrue("LANCZOS resize back drifted: max " + backDiff.max, backDiff.max <= 1)
    }

    private class Diff(val max: Int, val count: Int)

    private fun maxByteDiff(a: RgbaImage, b: RgbaImage): Diff {
        require(a.width == b.width && a.height == b.height) {
            "size mismatch " + a.width + "x" + a.height + " vs " + b.width + "x" + b.height
        }
        var max = 0
        var count = 0
        for (i in a.pixels.indices) {
            val d = abs((a.pixels[i].toInt() and 0xFF) - (b.pixels[i].toInt() and 0xFF))
            if (d > 0) count++
            if (d > max) max = d
        }
        return Diff(max, count)
    }

    private companion object {
        val TAGS = listOf("01ee25d8", "061d63a2", "4dde2cb0")
    }
}

/** Minimal PNG reader good enough for our own fixtures (8-bit RGB/RGBA, no interlacing). */
object Png {
    fun read(file: File): RgbaImage {
        val bytes = file.readBytes()
        require(bytes[0] == 0x89.toByte() && bytes[1] == 'P'.code.toByte()) { "not a PNG: " + file }
        var pos = 8
        var width = 0
        var height = 0
        var channels = 4
        val idat = java.io.ByteArrayOutputStream()
        while (pos < bytes.size) {
            val length = readInt(bytes, pos)
            val type = String(bytes, pos + 4, 4, Charsets.US_ASCII)
            val dataStart = pos + 8
            when (type) {
                "IHDR" -> {
                    width = readInt(bytes, dataStart)
                    height = readInt(bytes, dataStart + 4)
                    val bitDepth = bytes[dataStart + 8].toInt()
                    val colourType = bytes[dataStart + 9].toInt()
                    require(bitDepth == 8) { "only 8-bit PNG is supported, got $bitDepth" }
                    channels = when (colourType) {
                        2 -> 3
                        6 -> 4
                        0 -> 1
                        4 -> 2
                        else -> error("unsupported colour type $colourType")
                    }
                }
                "IDAT" -> idat.write(bytes, dataStart, length)
                "IEND" -> break
            }
            pos = dataStart + length + 4
        }
        val raw = java.util.zip.InflaterInputStream(idat.toByteArray().inputStream()).use { it.readBytes() }
        val stride = width * channels
        val out = ByteArray(width * height * 4)
        val previous = IntArray(stride)
        val current = IntArray(stride)
        var cursor = 0
        for (y in 0 until height) {
            val filter = raw[cursor++].toInt() and 0xFF
            for (i in 0 until stride) current[i] = raw[cursor + i].toInt() and 0xFF
            cursor += stride
            unfilter(filter, current, previous, channels)
            var o = y * width * 4
            for (x in 0 until width) {
                val i = x * channels
                when (channels) {
                    4 -> {
                        out[o] = current[i].toByte()
                        out[o + 1] = current[i + 1].toByte()
                        out[o + 2] = current[i + 2].toByte()
                        out[o + 3] = current[i + 3].toByte()
                    }
                    3 -> {
                        out[o] = current[i].toByte()
                        out[o + 1] = current[i + 1].toByte()
                        out[o + 2] = current[i + 2].toByte()
                        out[o + 3] = 0xFF.toByte()
                    }
                    1 -> {
                        out[o] = current[i].toByte()
                        out[o + 1] = current[i].toByte()
                        out[o + 2] = current[i].toByte()
                        out[o + 3] = 0xFF.toByte()
                    }
                    else -> {
                        out[o] = current[i].toByte()
                        out[o + 1] = current[i].toByte()
                        out[o + 2] = current[i].toByte()
                        out[o + 3] = current[i + 1].toByte()
                    }
                }
                o += 4
            }
            System.arraycopy(current, 0, previous, 0, stride)
        }
        return RgbaImage(width, height, out)
    }

    private fun unfilter(filter: Int, current: IntArray, previous: IntArray, bpp: Int) {
        when (filter) {
            0 -> {}
            1 -> for (i in bpp until current.size) current[i] = (current[i] + current[i - bpp]) and 0xFF
            2 -> for (i in current.indices) current[i] = (current[i] + previous[i]) and 0xFF
            3 -> for (i in current.indices) {
                val left = if (i >= bpp) current[i - bpp] else 0
                current[i] = (current[i] + ((left + previous[i]) shr 1)) and 0xFF
            }
            4 -> for (i in current.indices) {
                val a = if (i >= bpp) current[i - bpp] else 0
                val b = previous[i]
                val c = if (i >= bpp) previous[i - bpp] else 0
                current[i] = (current[i] + paeth(a, b, c)) and 0xFF
            }
            else -> error("bad PNG filter $filter")
        }
    }

    private fun paeth(a: Int, b: Int, c: Int): Int {
        val p = a + b - c
        val pa = abs(p - a)
        val pb = abs(p - b)
        val pc = abs(p - c)
        return if (pa <= pb && pa <= pc) a else if (pb <= pc) b else c
    }

    private fun readInt(bytes: ByteArray, at: Int): Int =
        ((bytes[at].toInt() and 0xFF) shl 24) or ((bytes[at + 1].toInt() and 0xFF) shl 16) or
            ((bytes[at + 2].toInt() and 0xFF) shl 8) or (bytes[at + 3].toInt() and 0xFF)
}

/** Minimal .npy reader for the float64 fixtures. */
object Npy {
    fun readFloatImage(file: File): FloatImage {
        val all = file.readBytes()
        require(all[0] == 0x93.toByte() && String(all, 1, 5, Charsets.US_ASCII) == "NUMPY") {
            "not a .npy file: " + file
        }
        val major = all[6].toInt()
        val headerLen: Int
        val headerStart: Int
        if (major == 1) {
            headerLen = (all[8].toInt() and 0xFF) or ((all[9].toInt() and 0xFF) shl 8)
            headerStart = 10
        } else {
            headerLen = (all[8].toInt() and 0xFF) or ((all[9].toInt() and 0xFF) shl 8) or
                ((all[10].toInt() and 0xFF) shl 16) or ((all[11].toInt() and 0xFF) shl 24)
            headerStart = 12
        }
        val header = String(all, headerStart, headerLen, Charsets.US_ASCII)
        val descr = Regex("'descr'\\s*:\\s*'([^']+)'").find(header)!!.groupValues[1]
        val shapeText = Regex("'shape'\\s*:\\s*\\(([^)]*)\\)").find(header)!!.groupValues[1]
        val shape = shapeText.split(',').mapNotNull { it.trim().toIntOrNull() }
        require(shape.size == 3) { "expected a 3-D array, got " + shape }
        require(!header.contains("True")) { "fortran order is not supported" }
        val h = shape[0]
        val w = shape[1]
        val c = shape[2]
        val dataStart = headerStart + headerLen
        val out = FloatImage(w, h)
        val little = java.nio.ByteBuffer.wrap(all).order(java.nio.ByteOrder.LITTLE_ENDIAN)
        for (y in 0 until h) {
            for (x in 0 until w) {
                val base = dataStart + ((y * w + x) * c) * 8
                val r = readValue(all, little, base, descr)
                val g = readValue(all, little, base + 8, descr)
                val b = readValue(all, little, base + 16, descr)
                val i = y * w + x
                out.r[i] = r.toFloat()
                out.g[i] = g.toFloat()
                out.b[i] = b.toFloat()
            }
        }
        return out
    }

    private fun readValue(bytes: ByteArray, buffer: java.nio.ByteBuffer, at: Int, descr: String): Double =
        when {
            descr.startsWith("<f8") || descr.startsWith("f8") -> buffer.getDouble(at)
            descr.startsWith("<f4") || descr.startsWith("f4") -> buffer.getFloat(at).toDouble()
            descr.startsWith("|u1") || descr.startsWith("u1") -> (bytes[at].toInt() and 0xFF).toDouble()
            else -> error("unsupported dtype $descr")
        }
}
